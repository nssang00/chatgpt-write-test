using System.Reflection;
using System.Text.Json;
using System.Text.RegularExpressions;

if (args.Length != 3) throw new ArgumentException("expected assembly, output folder, plugin ID");
var assembly = Assembly.LoadFrom(Path.GetFullPath(args[0]));
var pluginId = args[2];
var output = Path.GetFullPath(args[1]);
var reserved = new HashSet<string>(StringComparer.Ordinal) {
    "break","case","catch","class","const","continue","debugger","default",
    "delete","do","else","enum","export","extends","false","finally",
    "for","function","if","import","in","instanceof","new","null","return",
    "super","switch","this","throw","true","try","typeof","var","void",
    "while","with","yield","await","let","static","constructor","then",
    "__proto__","prototype"
};
string JsIdentifier(string value) {
    if (!Regex.IsMatch(value, @"\A[A-Za-z][A-Za-z0-9_]*\z") || reserved.Contains(value))
        throw new ArgumentException($"Unsupported JS export identifier: {value}");
    return value;
}
JsIdentifier(pluginId);
var exported = new List<object>();
var declarations = new List<string> { "// Generated by Xytron; edit the source plugin instead." };
var wrappers = new List<string> { "// Generated by Xytron; requires the Xytron window bridge." };
var names = new HashSet<string>(StringComparer.Ordinal);
static bool HasExport(MemberInfo m) => m.CustomAttributes.Any(
    a => a.AttributeType.FullName == "Xytron.ExportAttribute");
static string TsType(Type t) {
    if (t == typeof(void)) return "void";
    if (t == typeof(string)) return "string";
    if (t == typeof(bool)) return "boolean";
    if (t == typeof(byte[])) return "Uint8Array";
    if (t == typeof(int) || t == typeof(long) || t == typeof(short) ||
        t == typeof(double) || t == typeof(float)) return "number";
    throw new NotSupportedException($"Unsupported export type: {t.FullName}");
}
foreach (var t in assembly.GetExportedTypes().OrderBy(x => x.FullName, StringComparer.Ordinal)) {
    if (HasExport(t)) throw new NotSupportedException($"Exported class not supported yet: {t.FullName}");
    foreach (var m in t.GetMethods(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly)
                        .Where(HasExport).OrderBy(m => m.Name, StringComparer.Ordinal)) {
        JsIdentifier(m.Name);
        if (!names.Add(m.Name)) throw new NotSupportedException($"Overloaded/duplicate export: {m.Name}");
        if (m.IsGenericMethod || m.ContainsGenericParameters)
            throw new NotSupportedException($"Generic exports unsupported: {m.Name}");
        var ps = m.GetParameters();
        if (ps.Any(p => p.IsOptional || p.IsOut || p.ParameterType.IsByRef))
            throw new NotSupportedException($"ByRef/optional parameter unsupported: {m.Name}");
        var types = ps.Select(p => TsType(p.ParameterType)).ToArray();
        var paramNames = ps.Select(p => JsIdentifier(p.Name ?? throw new ArgumentException("unnamed parameter"))).ToArray();
        var result = TsType(m.ReturnType);
        if (types.Contains("void")) throw new NotSupportedException("void parameter type not allowed");
        exported.Add(new { name = m.Name, arguments = types, parameterNames = paramNames, returns = result });
        declarations.Add($"export declare function {m.Name}(" +
            string.Join(", ", paramNames.Zip(types, (n, ty) => $"{n}: {ty}")) +
            $"): Promise<{result}>;");
        var full = JsonSerializer.Serialize(pluginId + "." + m.Name);
        wrappers.Add($"export function {m.Name}(...args) {{\n" +
            "  const bridge = globalThis.xytron;\n" +
            "  if (!bridge || typeof bridge.invoke !== 'function')\n" +
            "    throw new Error('Xytron bridge unavailable');\n" +
            $"  return bridge.invoke({full}, ...args);\n" +
            "}");
    }
}
if (exported.Count == 0) throw new ArgumentException("No exported static methods found");
var doc = new { schemaVersion = 1, runtime = "dotnet", pluginId, functions = exported };
Directory.CreateDirectory(output);
if (new DirectoryInfo(output).LinkTarget is not null)
    throw new IOException("Output directory symlink forbidden");
var targets = new[] { Path.Combine(output, "exports.json"), Path.Combine(output, "index.d.ts"), Path.Combine(output, "index.mjs") };
if (targets.Any(File.Exists)) throw new IOException("Refusing to overwrite existing generated bindings");
var content = new[] { JsonSerializer.Serialize(doc, new JsonSerializerOptions { WriteIndented = true }) + "\n",
                      string.Join("\n", declarations) + "\n", string.Join("\n", wrappers) + "\n" };
for (int i = 0; i < targets.Length; ++i) {
    using var file = new FileStream(targets[i], FileMode.CreateNew, FileAccess.Write, FileShare.None);
    using var writer = new StreamWriter(file);
    writer.Write(content[i]);
}
Console.WriteLine($"Generated dotnet typed bindings for {exported.Count} function(s): {output}");
