using System.Reflection;
using System.Text.Json;
using System.Text.RegularExpressions;

// This tool loads a trusted local assembly. Never run it on untrusted plugins.
if (args.Length != 3) throw new ArgumentException("expected assembly, output folder, plugin ID");
var assembly = Assembly.LoadFrom(Path.GetFullPath(args[0]));
var output = Path.GetFullPath(args[1]);
var pluginId = args[2];
var reserved = new HashSet<string>(StringComparer.Ordinal) {
    "break","case","catch","class","const","continue","debugger","default",
    "delete","do","else","enum","export","extends","false","finally",
    "for","function","if","import","in","instanceof","new","null","return",
    "super","switch","this","throw","true","try","typeof","var","void",
    "while","with","yield","await","let","static","constructor","then",
    "__proto__","prototype"
};
string Id(string value) {
    if (!Regex.IsMatch(value, @"\A[A-Za-z][A-Za-z0-9_]*\z") || reserved.Contains(value))
        throw new ArgumentException($"Unsupported JS export identifier: {value}");
    return value;
}
Id(pluginId);
static bool Exported(MemberInfo member) => member.CustomAttributes.Any(
    a => a.AttributeType.FullName == "Xytron.ExportAttribute");
static string TypeName(Type t) {
    if (t == typeof(void)) return "void";
    if (t == typeof(string)) return "string";
    if (t == typeof(bool)) return "boolean";
    if (t == typeof(byte[])) return "Uint8Array";
    if (t == typeof(int) || t == typeof(long) || t == typeof(short) ||
        t == typeof(float) || t == typeof(double)) return "number";
    throw new NotSupportedException($"Unsupported export type: {t.FullName}");
}
(string[] types, string[] names) Parameters(ParameterInfo[] ps) {
    if (ps.Any(p => p.IsOptional || p.IsOut || p.ParameterType.IsByRef || p.HasDefaultValue))
        throw new NotSupportedException("Optional/byref parameters unsupported");
    var types=ps.Select(p=>TypeName(p.ParameterType)).ToArray();
    if (types.Contains("void")) throw new NotSupportedException("void parameter type unsupported");
    return (types, ps.Select(p=>Id(p.Name ?? throw new ArgumentException("Unnamed parameter"))).ToArray());
}
string Sig(string[] names, string[] types) => string.Join(", ", names.Zip(types, (n,t)=>$"{n}: {t}"));
string Full(string method) => JsonSerializer.Serialize(pluginId+"."+method);
string InvokeCheck() => "    const bridge = globalThis.xytron;\n" +
    "    if (!bridge || typeof bridge.invoke !== 'function') throw new Error('Xytron bridge unavailable');\n";
var functions = new List<object>();
var classes = new List<object>();
var dts = new List<string> { "// Generated by Xytron; edit the source plugin instead." };
var mjs = new List<string> { "// Generated by Xytron; requires the Xytron window bridge.",
    "// Class calls require a managed object host (not yet available)." };
var names = new HashSet<string>(StringComparer.Ordinal);
foreach (var t in assembly.GetExportedTypes().OrderBy(t=>t.FullName, StringComparer.Ordinal)) {
    foreach (var m in t.GetMethods(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly)
                    .Where(Exported).OrderBy(m=>m.Name,StringComparer.Ordinal)) {
        var name = Id(m.Name);
        if (!names.Add(name)) throw new NotSupportedException($"Overloaded/duplicate export: {name}");
        if (m.IsGenericMethod || m.ContainsGenericParameters)
            throw new NotSupportedException($"Generic exports unsupported: {name}");
        var (types,parameterNames)=Parameters(m.GetParameters());
        var returns=TypeName(m.ReturnType);
        functions.Add(new { name, arguments=types, parameterNames, returns });
        dts.Add($"export declare function {name}({Sig(parameterNames,types)}): Promise<{returns}>;");
        mjs.Add($"export function {name}(...args) {{\n" + InvokeCheck() +
                $"    return bridge.invoke({Full(name)}, ...args);\n" + "}");
    }
    if (!Exported(t)) continue;
    var className=Id(t.Name);
    if (!names.Add(className)) throw new NotSupportedException($"Duplicate export: {className}");
    if (!t.IsClass || t.IsAbstract || t.ContainsGenericParameters)
        throw new NotSupportedException($"Unsupported exported class: {className}");
    var publicConstructors=t.GetConstructors(BindingFlags.Public | BindingFlags.Instance);
    var markedConstructors=publicConstructors.Where(Exported).ToArray();
    if (markedConstructors.Length>1) throw new NotSupportedException("Constructor overload unsupported");
    ConstructorInfo ctor;
    if (markedConstructors.Length==1) ctor=markedConstructors[0];
    else ctor=publicConstructors.SingleOrDefault(c=>c.GetParameters().Length==0)
              ?? throw new NotSupportedException("Parameterized constructor must use [Export]");
    var (ctorTypes,ctorNames)=Parameters(ctor.GetParameters());
    var methods = new List<object>();
    var props = new List<object>();
    var used = new HashSet<string>(StringComparer.Ordinal) { "create", "dispose" };
    dts.Add($"export declare class {className} {{");
    dts.Add("  private constructor();");
    dts.Add($"  static create({Sig(ctorNames,ctorTypes)}): Promise<{className}>;");
    mjs.Add($"export class {className} {{\n" +
        "  #handle;\n"+
        "  constructor(handle) { this.#handle = handle; }\n"+
        "  static async create(...args) {\n"+InvokeCheck()+
        $"    const handle = await bridge.invoke({Full(className+".create")}, ...args);\n"+
        "    if (typeof handle !== 'string' || !handle) throw new Error('Invalid managed object handle');\n"+
        $"    return new {className}(handle);\n"+
        "  }\n"+
        "  #active() {\n"+
        "    if (this.#handle === null) throw new Error('Xytron object already disposed');\n"+
        "    const bridge = globalThis.xytron;\n"+
        "    if (!bridge || typeof bridge.invoke !== 'function') throw new Error('Xytron bridge unavailable');\n"+
        "    return bridge;\n"+
        "  }");
    foreach (var method in t.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
                             .Where(m=>!m.IsSpecialName && Exported(m)).OrderBy(m=>m.Name,StringComparer.Ordinal)) {
        var n=Id(method.Name);
        if (!used.Add(n)) throw new NotSupportedException($"Duplicate/reserved instance method: {n}");
        if (method.IsGenericMethod || method.ContainsGenericParameters)
            throw new NotSupportedException("Generic instance methods unsupported");
        var (paramTypes,paramNames)=Parameters(method.GetParameters());
        var result=TypeName(method.ReturnType);
        methods.Add(new { name=n, arguments=paramTypes, parameterNames=paramNames, returns=result });
        dts.Add($"  {n}({Sig(paramNames,paramTypes)}): Promise<{result}>;");
        mjs.Add($"  {n}(...args) {{\n"+
                "    const bridge = this.#active();\n"+
                $"    return bridge.invoke({Full(className+".method."+n)}, this.#handle, ...args);\n"+
                "  }");
    }
    foreach (var prop in t.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
                          .Where(Exported).OrderBy(p=>p.Name,StringComparer.Ordinal)) {
        var n=Id(prop.Name);
        if (prop.GetIndexParameters().Length>0) throw new NotSupportedException("Indexer exports unsupported");
        var ty=TypeName(prop.PropertyType);
        if (ty=="void") throw new NotSupportedException("void property unsupported");
        bool readable=prop.GetMethod?.IsPublic==true;
        bool writable=prop.SetMethod?.IsPublic==true;
        if (!readable && !writable) throw new NotSupportedException("Property requires public accessor");
        props.Add(new { name=n, type=ty, readable, writable });
        var cap=n.Substring(0,1).ToUpperInvariant()+n.Substring(1);
        foreach (var action in new[] { "get", "set" }) {
            if ((action=="get" && !readable)||(action=="set" && !writable)) continue;
            var accessor=action+cap;
            if (!used.Add(accessor)) throw new NotSupportedException($"Accessor collision: {accessor}");
            var param=(action=="get")?"":$"value: {ty}";
            var result=(action=="get")?ty:"void";
            dts.Add($"  {accessor}({param}): Promise<{result}>;");
            mjs.Add($"  {accessor}({(action=="get"?"":"value")}) {{\n"+
                    "    const bridge = this.#active();\n"+
                    $"    return bridge.invoke({Full(className+"."+action+"."+n)}, this.#handle{(action=="get"?"":", value")});\n"+
                    "  }");
        }
    }
    if (methods.Count==0 && props.Count==0)
        throw new NotSupportedException($"Exported class must explicitly export members: {className}");
    classes.Add(new { name=className, constructor=new { arguments=ctorTypes, parameterNames=ctorNames }, methods, properties=props });
    dts.Add("  dispose(): Promise<void>;");dts.Add("}");
    mjs.Add("  async dispose() {\n"+
            "    if (this.#handle === null) return;\n"+
            "    const bridge = this.#active();\n"+
            $"    await bridge.invoke({Full(className+".dispose")}, this.#handle);\n"+
            "    this.#handle = null;\n"+
            "  }\n"+
            "}");
}
if (functions.Count==0 && classes.Count==0) throw new ArgumentException("No exported methods/classes found");
Directory.CreateDirectory(output);
if (new DirectoryInfo(output).LinkTarget is not null) throw new IOException("Output directory symlink forbidden");
var targets=new[] { Path.Combine(output,"exports.json"),Path.Combine(output,"index.d.ts"),Path.Combine(output,"index.mjs") };
if (targets.Any(File.Exists)) throw new IOException("Refusing to overwrite existing generated bindings");
var document = new Dictionary<string,object> { ["schemaVersion"]=1,["runtime"]="dotnet",["pluginId"]=pluginId,
    ["functions"]=functions };
if (classes.Count>0) document["classes"]=classes;
var content=new[] { JsonSerializer.Serialize(document,new JsonSerializerOptions{WriteIndented=true})+"\n",
    string.Join("\n",dts)+"\n",string.Join("\n",mjs)+"\n" };
for(int i=0;i<targets.Length;i++){
    using var stream=new FileStream(targets[i],FileMode.CreateNew,FileAccess.Write,FileShare.None);
    using var writer=new StreamWriter(stream);
    writer.Write(content[i]);
}
Console.WriteLine($"Generated dotnet typed bindings for {functions.Count} functions, {classes.Count} classes: {output}");
